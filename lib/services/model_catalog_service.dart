  /// Search and filter catalog items across multi-dimensional criteria
  static List<ModelCatalogItem> searchModels({
    String query = '',
    String category = 'All',
    String sizeFilter = 'All', // Legacy: 'All', 'Lightweight', 'Medium', 'Large'
    bool hardwareCompatibleOnly = false,
    double? systemRamGb,
    List<String>? installedModelIds,
    String statusFilter = 'All', // 'All', 'Installed', 'Not Installed', 'Favorites'
    List<String>? favoriteIds,
    String sortBy = 'Popularity', // 'Popularity', 'Name', 'Size', 'Context'
    String sizeTier = 'All', // 'All', 'Ultra-light', 'Lightweight', 'Medium', 'Advanced', 'Large', 'Extra-large'
    String familyFilter = 'All',
    String ragRoleFilter = 'All',
    String modalityFilter = 'All',
    String taskFilter = 'All',
    String verificationFilter = 'All',
  }) {
    List<ModelCatalogItem> results = List.from(getAllModels());

    // 1. Search Query Filter
    final q = query.trim().toLowerCase();
    if (q.isNotEmpty) {
      results = results.where((m) {
        return m.name.toLowerCase().contains(q) ||
            m.id.toLowerCase().contains(q) ||
            m.family.toLowerCase().contains(q) ||
            m.provider.toLowerCase().contains(q) ||
            m.architecture.toLowerCase().contains(q) ||
            m.capabilities.any((c) => c.toLowerCase().contains(q)) ||
            m.supportedTasks.any((t) => t.toLowerCase().contains(q)) ||
            m.description.toLowerCase().contains(q);
      }).toList();
    }

    // 2. Category Filter
    if (category != 'All') {
      results = results.where((m) => m.category == category).toList();
    }

    // 3. Size Filter (Legacy compatibility)
    if (sizeFilter == 'Lightweight') {
      results = results.where((m) => m.estimatedMemoryGb <= 3.0).toList();
    } else if (sizeFilter == 'Medium') {
      results = results.where((m) => m.estimatedMemoryGb > 3.0 && m.estimatedMemoryGb <= 12.0).toList();
    } else if (sizeFilter == 'Large') {
      results = results.where((m) => m.estimatedMemoryGb > 12.0).toList();
    }

    // 4. Granular Size Tier Filter
    if (sizeTier != 'All') {
      results = results.where((m) {
        if (sizeTier == 'Ultra-light') {
          return m.sizeTier == 'Ultra-light' || m.isUltraLight;
        }
        return m.sizeTier == sizeTier;
      }).toList();
    }

    // 5. Family Filter
    if (familyFilter != 'All') {
      final fLower = familyFilter.toLowerCase();
      results = results.where((m) => m.family.toLowerCase() == fLower).toList();
    }

    // 6. RAG Role Filter
    if (ragRoleFilter != 'All') {
      results = results.where((m) => m.ragRole == ragRoleFilter).toList();
    }

    // 7. Modality Filter
    if (modalityFilter != 'All') {
      results = results.where((m) => m.supportedModalities.contains(modalityFilter)).toList();
    }

    // 8. Task Filter
    if (taskFilter != 'All') {
      results = results.where((m) => m.supportedTasks.contains(taskFilter)).toList();
    }

    // 9. Verification Status Filter
    if (verificationFilter != 'All') {
      results = results.where((m) => m.verificationStatus == verificationFilter).toList();
    }

    // 10. Hardware Compatibility Filter
    if (hardwareCompatibleOnly && systemRamGb != null && systemRamGb > 0) {
      results = results.where((m) => m.estimatedMemoryGb <= systemRamGb * 0.9).toList();
    }

    // 11. Status Filter
    if (statusFilter == 'Installed' && installedModelIds != null) {
      results = results.where((m) {
        final idLower = m.id.toLowerCase();
        return installedModelIds.any((inst) => inst.toLowerCase() == idLower || inst.toLowerCase().startsWith('$idLower:'));
      }).toList();
    } else if (statusFilter == 'Not Installed' && installedModelIds != null) {
      results = results.where((m) {
        final idLower = m.id.toLowerCase();
        return !installedModelIds.any((inst) => inst.toLowerCase() == idLower || inst.toLowerCase().startsWith('$idLower:'));
      }).toList();
    } else if (statusFilter == 'Favorites' && favoriteIds != null) {
      results = results.where((m) => favoriteIds.contains(m.id)).toList();
    }

    // 12. Sorting
    if (sortBy == 'Name') {
      results.sort((a, b) => a.name.compareTo(b.name));
    } else if (sortBy == 'Size') {
      results.sort((a, b) => a.estimatedMemoryGb.compareTo(b.estimatedMemoryGb));
    } else if (sortBy == 'Context') {
      results.sort((a, b) => b.contextLength.compareTo(a.contextLength));
    }

    return results;
  }

  /// Retrieve model by exact or prefix ID
  static ModelCatalogItem? getModelById(String id) {
    try {
      final idLower = id.toLowerCase();
      return _catalog.firstWhere((m) {
        final mLower = m.id.toLowerCase();
        return mLower == idLower || idLower.startsWith('$mLower:');
      });
    } catch (_) {
      return null;
    }
  }
